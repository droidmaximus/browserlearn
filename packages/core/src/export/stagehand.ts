import type { Locator, Workflow, WorkflowStep } from "../types.js";

const q = (s: string): string => JSON.stringify(s);
const oneLine = (s: string): string => s.replace(/\s+/g, " ").trim();

function actTarget(l: Locator): string {
  switch (l.kind) {
    case "testId":
      return `element with test id "${l.testId}"`;
    case "role":
      return `"${l.name}" ${l.role}`;
    case "css":
      return `element matching "${l.css}"`;
    case "xpath":
      return `element at xpath "${l.xpath}"`;
  }
}

function stepLines(s: WorkflowStep): string[] {
  const out = [`  // ${oneLine(s.name)}`];
  if (s.action === "navigate") {
    out.push(`  await page.goto(${q(s.url ?? "")});`);
    return out;
  }
  if (!s.locator) {
    out.push(`  throw new Error(${q(`Step "${oneLine(s.name)}" has no locator`)});`);
    return out;
  }
  const target = actTarget(s.locator);
  const vars = s.param ? `, { variables: { ${q(s.param)}: params[${q(s.param)}] } }` : "";
  const instruction = {
    click: `click the ${target}`,
    type: `type %${s.param}% into the ${target}`,
    select: `select %${s.param}% in the ${target}`,
    submit: `submit the ${target}`,
  }[s.action];
  out.push(`  await stagehand.act(${q(instruction)}${vars});`);
  return out;
}

export function exportStagehand(w: Workflow): string {
  const required = JSON.stringify(w.params.filter((p) => p.required).map((p) => p.name));
  return [
    `import { Stagehand } from "@browserbasehq/stagehand";`,
    ``,
    `// Generated by BrowserLearn from workflow ${q(oneLine(w.name))} v${w.version}`,
    `// Usage: node workflow.mjs '{"param": "value"}'`,
    `const params = JSON.parse(process.argv[2] ?? "{}");`,
    `for (const name of ${required}) {`,
    "  if (!(name in params)) throw new Error(`Missing parameter: ${name}`);",
    `}`,
    ``,
    `const stagehand = new Stagehand({ env: "LOCAL" });`,
    `await stagehand.init();`,
    `const page = stagehand.context.pages()[0];`,
    `try {`,
    ...w.steps.flatMap(stepLines),
    `} finally {`,
    `  await stagehand.close();`,
    `}`,
    ``,
  ].join("\n");
}
