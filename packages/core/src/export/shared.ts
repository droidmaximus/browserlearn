import type { ParamDef, Workflow, WorkflowStep } from "../types.js";

export const q = (s: string): string => JSON.stringify(s);
export const oneLine = (s: string): string => s.replace(/\s+/g, " ").trim();

export const paramRef = (name: string): string => `params[${q(name)}]`;

interface Chunk {
  text: string;
  param?: string;
}

interface Needle {
  param: string;
  needle: string;
}

function needles(params: ParamDef[]): Needle[] {
  return params
    .flatMap((p) => {
      const ex = p.example;
      if (p.secret || ex === undefined || ex.length < 3) return [];
      const enc = encodeURIComponent(ex);
      const forms = new Set([ex, enc, ex.replace(/ /g, "+"), enc.replace(/%20/g, "+")]);
      return [...forms].map((f) => ({ param: p.name, needle: f.toLowerCase() }));
    })
    .sort((a, b) => b.needle.length - a.needle.length);
}

/** Splits text into literal chunks and case-insensitive occurrences of non-secret param examples. */
function splitOnExamples(text: string, params: ParamDef[]): Chunk[] {
  const all = needles(params);
  const chunks: Chunk[] = [];
  let literal = "";
  for (let i = 0; i < text.length; ) {
    const hit = all.find((n) => text.slice(i, i + n.needle.length).toLowerCase() === n.needle);
    if (!hit) {
      literal += text[i];
      i++;
      continue;
    }
    if (literal) chunks.push({ text: literal });
    literal = "";
    chunks.push({ text: text.slice(i, i + hit.needle.length), param: hit.param });
    i += hit.needle.length;
  }
  if (literal || chunks.length === 0) chunks.push({ text: literal });
  return chunks;
}

/** A JS expression for a URL, with param examples replaced by the encoded runtime param value. */
export function urlExpr(url: string, params: ParamDef[]): string {
  return splitOnExamples(url, params)
    .map((c) => (c.param ? `encodeURIComponent(${paramRef(c.param)})` : q(c.text)))
    .join(" + ");
}

/** Comment-safe text: one line, with param examples replaced by `{name}`. */
export function commentText(text: string, params: ParamDef[]): string {
  return oneLine(
    splitOnExamples(text, params)
      .map((c) => (c.param ? `{${c.param}}` : c.text))
      .join(""),
  );
}

export const noLocatorLine = (s: WorkflowStep, params: ParamDef[]): string =>
  `  throw new Error(${q(`Step "${commentText(s.name, params)}" has no locator`)});`;

/** Throws if a type/select step does not reference a declared param. */
export function checkStepParams(w: Workflow): void {
  const declared = new Set(w.params.map((p) => p.name));
  for (const s of w.steps) {
    if ((s.action === "type" || s.action === "select") && !(s.param && declared.has(s.param))) {
      throw new Error(`Step "${s.name}" needs a parameter`);
    }
  }
}

export function scriptHeader(w: Workflow, importLine: string): string {
  return [
    importLine,
    ``,
    `// Generated by BrowserLearn from workflow ${q(commentText(w.name, w.params))} v${w.version}`,
    `// Usage: node workflow.mjs '{"param": "value"}'`,
    paramsPreamble(w),
  ].join("\n");
}

export function paramsPreamble(w: Workflow): string {
  const required = JSON.stringify(w.params.filter((p) => p.required).map((p) => p.name));
  return [
    `const params = JSON.parse(process.argv[2] ?? "{}");`,
    `if (typeof params !== "object" || params === null || Array.isArray(params)) {`,
    `  throw new Error("Parameters must be a JSON object");`,
    `}`,
    `for (const name of ${required}) {`,
    "  if (!Object.hasOwn(params, name)) throw new Error(`Missing parameter: ${name}`);",
    `}`,
    `for (const [name, value] of Object.entries(params)) {`,
    "  if (typeof value !== \"string\") throw new Error(`Parameter ${name} must be a string`);",
    `}`,
  ].join("\n");
}
