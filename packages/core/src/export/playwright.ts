import type { Locator, Workflow, WorkflowStep } from "../types.js";

const q = (s: string): string => JSON.stringify(s);
const oneLine = (s: string): string => s.replace(/\s+/g, " ").trim();

export function locatorExpr(l: Locator, framePath: number[]): string {
  const base = framePath.reduce((acc, i) => `${acc}.frameLocator(${q(`iframe >> nth=${i}`)})`, "page");
  switch (l.kind) {
    case "testId":
      return `${base}.getByTestId(${q(l.testId)})`;
    case "role":
      return `${base}.getByRole(${q(l.role)}, { name: ${q(l.name)}, exact: true })`;
    case "css":
      return `${base}.locator(${q(l.css)})`;
    case "xpath":
      return `${base}.locator(${q(`xpath=${l.xpath}`)})`;
  }
}

function stepLines(s: WorkflowStep): string[] {
  const out = [`  // ${oneLine(s.name)}`];
  const value = `params[${q(s.param ?? "")}]`;
  if (s.action === "navigate") {
    out.push(`  await page.goto(${q(s.url ?? "")});`);
  } else if (!s.locator) {
    out.push(`  throw new Error(${q(`Step "${oneLine(s.name)}" has no locator`)});`);
  } else {
    const loc = locatorExpr(s.locator, s.framePath);
    if (s.action === "click") out.push(`  await ${loc}.click();`);
    if (s.action === "type") out.push(`  await ${loc}.fill(${value});`);
    if (s.action === "select") out.push(`  await ${loc}.selectOption(${value});`);
    if (s.action === "submit") out.push(`  await ${loc}.evaluate((form) => form.requestSubmit());`);
  }
  if (s.expected.urlPath) {
    out.push(`  await page.waitForURL((u) => u.origin + u.pathname === ${q(s.expected.urlPath)});`);
  }
  return out;
}

export function exportPlaywright(w: Workflow): string {
  const required = JSON.stringify(w.params.filter((p) => p.required).map((p) => p.name));
  return [
    `import { chromium } from "playwright";`,
    ``,
    `// Generated by BrowserLearn from workflow ${q(oneLine(w.name))} v${w.version}`,
    `// Usage: node workflow.mjs '{"param": "value"}'`,
    `const params = JSON.parse(process.argv[2] ?? "{}");`,
    `for (const name of ${required}) {`,
    "  if (!(name in params)) throw new Error(`Missing parameter: ${name}`);",
    `}`,
    ``,
    `const browser = await chromium.launch({ headless: false });`,
    `const page = await browser.newPage();`,
    `try {`,
    ...w.steps.flatMap(stepLines),
    `} finally {`,
    `  await browser.close();`,
    `}`,
    ``,
  ].join("\n");
}
